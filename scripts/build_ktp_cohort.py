"""Builds the SQL that adds the 2025-26 Grade 11 KTP as the Grade 11 plan of the
students now in Grade 12 (they were taught by it last year).

The plan reuses the topics already on the site (their theory and questions);
it only adds grades/terms/units rows and school_placements.

    python3 -I scripts/build_ktp_cohort.py docs/source/KTP_11_Computer_Science_2025-2026.docx \
        > supabase/migrations/20261027000019_ktp_2025_26_cohort_plan.sql
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import import_curriculum as ic  # noqa: E402

VERSION = "NIS_CS_2026_2027"
FOR_GRADE = 12
TITLE = "Grade 11 · KTP 2025–26"

# KTP lesson (title prefix) -> site topics that teach it. A topic is placed once
# per unit: a later lesson of the same unit that maps to it is merged into it.
# The KTP teaches DFDs and flowcharts in both 11.1C and 11.2B, so they appear twice.
MAP = [
    ("Software categories", ["g11-software-classification"]),
    ("Operating systems", ["g11-operating-systems"]),
    ("Von Neumann", ["paper-cpu-memory-and-peripherals"]),
    ("Memory types", ["paper-cpu-memory-and-peripherals"]),
    ("Laws of Boolean logic", ["g12-boolean-logic"]),
    ("Classifications and categories", ["g11-classification-of-programming-languages"]),
    ("Translators", ["paper-translators-and-language-generations"]),
    ("Assembler", ["paper-assembly-and-trace-tables"]),
    ("System life cycle stages", ["g11-sdlc-models"]),
    ("System life cycle models", ["g11-sdlc-models"]),
    ("Data analysis", ["g11-data-analysis"]),
    ("Process flowcharts", ["g11-process-design", "g11-designing-a-new-system-dfd"]),
    ("Database basics", ["g11-basic-concepts-of-a-database", "g11-data-dictionary"]),
    ("Entity Relationship", ["g11-entity-relationship-diagram", "g11-database-design"]),
    ("Normalisation", ["g11-normalization"]),
    ("SQL query", ["g11-sql"]),
    ("Data flow diagrams", ["g11-designing-a-new-system-dfd"]),
    ("Flowcharts of processes", ["g11-process-design"]),
    ("Prototyping", ["g11-prototyping"]),
    ("Advantages and limitations", ["paper-new-system-analysis"]),
    ("Development environment", ["paper-new-system-analysis"]),
    ("Technical specification", ["g11-technical-specification"]),
    ("The structure of one-dimensional", ["paper-arrays"]),
    ("Search and sort", ["paper-sorting-and-searching"]),
    ("Algorithm efficiency", ["paper-algorithm-efficiency"]),
    ("HTML markup", ["g11-web-page-design"]),
    ("CSS", ["g11-cascading-style-sheets"]),
    ("Script language", ["g11-scripting-language"]),
    ("Using scripts", ["g11-html-form-processing", "g11-adding-and-selecting-data-from-a-database"]),
    ("Application interface", ["g11-user-interfaces"]),
    ("Mobile application development", ["paper-mobile-application-development"]),
    ("Publishing mobile", ["paper-mobile-application-development"]),
    ("Project development", ["g11-web-application-development", "g11-database-development", "g11-sql-implementation"]),
    ("Security, privacy", ["g11-information-protection-measures"]),
    ("Safety methods", ["g11-physical-risks", "g11-malware"]),
    ("Validation and verification", ["g11-data-testing", "g11-types-of-programming-errors"]),
    ("Blockchain", ["paper-blockchain"]),
    ("Ethics and ownership", ["paper-ethics-and-ownership"]),
    ("Computer networks", ["g11-computer-networks", "g11-network-devices"]),
    ("Principles of Internet", ["g11-packet-routing", "g11-domain-name-system"]),
    ("Protocols", ["paper-ip-addressing"]),
]
ROMAN = {1: "I", 2: "II", 3: "III", 4: "IV"}


def q(s):
    return "null" if s in (None, "") else "'" + str(s).replace("'", "''") + "'"


def topics_for(title):
    for prefix, slugs in MAP:
        if title.startswith(prefix):
            return slugs
    raise SystemExit(f"no site topic for KTP lesson {title!r}")


def main(path):
    # The 2025-26 file writes unit headings as "Unit 11.1B: ..." and has no Term IV row.
    src = Path(ic.__file__).read_text().replace(
        r'r"^(\d{2}\.\d[A-ZА-Я])\s*:?\s*(.+)$"', r'r"^(?:Unit\s+)?(\d{2}\.\d[A-ZА-Я])\s*:?\s*(.+)$"'
    )
    ns = {"__name__": "ic"}
    exec(compile(src, ic.__file__, "exec"), ns)
    terms, _, _ = ns["parse_ktp"](path, 11)
    units = [u for t in terms for u in t["units"]]
    by_term = {}
    for u in units:
        by_term.setdefault(int(u["code"][3]), []).append(u)

    out = [
        "-- The 2025-26 Grade 11 KTP, kept as the Grade 11 plan of the students who are",
        "-- now in Grade 12 (generated by scripts/build_ktp_cohort.py). It reuses the",
        "-- topics already on the site; nothing happens where the programme is missing.",
        "do $$",
        "declare v uuid; g uuid; t uuid; u uuid;",
        "begin",
        f"  select id into v from public.curriculum_versions where code = '{VERSION}';",
        "  if v is null then return; end if;",
        f"  delete from public.grades where curriculum_version_id = v and number = 11 and for_student_grade = {FOR_GRADE};",
        f"  insert into public.grades (curriculum_version_id, number, title, total_hours, sort_order, for_student_grade)",
        f"    values (v, 11, {q(TITLE)}, 210, 5, {FOR_GRADE}) returning id into g;",
    ]
    for tn in sorted(by_term):
        hours = sum(tp["hours"] or 0 for u in by_term[tn] for tp in u["topics"])
        out.append(f"  insert into public.terms (grade_id, number, title, hours, sort_order) values (g, {tn}, 'Term {ROMAN[tn]}', {hours}, {tn}) returning id into t;")
        for ui, un in enumerate(by_term[tn]):
            out.append(f"  insert into public.units (term_id, code, title, sort_order) values (t, {q(un['code'])}, {q(un['title'].strip())}, {ui}) returning id into u;")
            placed = {}
            for tp in un["topics"]:
                for slug in topics_for(tp["title"]):
                    p = placed.setdefault(slug, {"lessons": [], "hours": 0, "period": [], "resources": []})
                    if tp["lessons"]:
                        p["lessons"].append(tp["lessons"])
                    p["hours"] += tp["hours"] or 0
                    if tp["period"]:
                        p["period"].append(tp["period"])
                    if tp["resources"]:
                        p["resources"].append(tp["resources"])
            for i, (slug, p) in enumerate(placed.items()):
                lessons = ", ".join(dict.fromkeys(p["lessons"])) or None
                period = re.sub(r"\s+", " ", "; ".join(dict.fromkeys(p["period"]))) or None
                resources = "\n".join(dict.fromkeys(p["resources"])) or None
                out.append(
                    "  insert into public.school_placements (topic_id, unit_id, lessons, hours, period, resources, sort_order)"
                    f" select id, u, {q(lessons)}, {p['hours'] or 'null'}, {q(period)}, {q(resources)}, {i}"
                    f" from public.topics where curriculum_version_id = v and slug = '{slug}';"
                )
    out += ["end $$;", ""]
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
